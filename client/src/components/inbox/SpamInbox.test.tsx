import { act, cleanup, render, screen, fireEvent, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import SpamInbox from "./SpamInbox";
import { useAuthStore } from "../../stores/authStore";
import { useSpamDecisionStore } from "../../stores/spamDecisionStore";
import { listSpam, listSpamDecisions, decideSpam, type SpamEntry } from "../../api/spam";
import { clearTokens } from "../../api/client";
vi.mock("../../api/spam", () => ({ listSpam: vi.fn(), listSpamDecisions: vi.fn(), decideSpam: vi.fn() }));
vi.mock("../../hooks/useOpenAtMessage", () => ({ useOpenAtMessage: () => ({ openAtMessage: vi.fn(), openAtDMMessage: vi.fn() }) }));
vi.mock("react-i18next", () => ({ useTranslation: () => ({ t: (key: string) => key }), initReactI18next: { type: "3rdParty", init: () => {} } }));
const entry: SpamEntry = { source_kind: "dm", channel_id: "private", message_id: "message", revision: "original", reasons: ["credential-link"], status: "quarantined", created_at: "2026-10-24T00:00:00Z" };
beforeEach(() => {
  cleanup();
  vi.clearAllMocks();
  useAuthStore.setState({ user: { id: "reader" } as NonNullable<ReturnType<typeof useAuthStore.getState>["user"]> });
  useSpamDecisionStore.setState({ accountId: null, decisions: {}, syncError: false });
  vi.mocked(listSpam).mockResolvedValue({ success: true, data: { entries: [entry] } });
  vi.mocked(decideSpam).mockResolvedValue({ success: true });
  vi.mocked(listSpamDecisions).mockResolvedValue({success:true,data:{entries:[]}});
});
afterEach(() => cleanup());
it("keeps a successful decision hidden when a stale refresh arrives without a socket event", async () => {
  useAuthStore.setState({ user: { id: "reader" } as NonNullable<ReturnType<typeof useAuthStore.getState>["user"]> });
  let finish!: (value: Awaited<ReturnType<typeof listSpam>>) => void;
  vi.mocked(listSpam).mockResolvedValueOnce({ success: true, data: { entries: [entry] } });
  vi.mocked(listSpam).mockReturnValueOnce(new Promise((resolve) => { finish = resolve; }));
  render(<SpamInbox />);
  await screen.findByRole("button", { name: "spamDismiss" });
  fireEvent.click(screen.getByRole("button", { name: "spamRefresh" }));
  fireEvent.click(screen.getByRole("button", { name: "spamDismiss" }));
  await waitFor(() => expect(screen.queryByText("spamReference")).not.toBeInTheDocument());
  await act(async () => { finish({ success: true, data: { entries: [entry] } }); });
  expect(screen.queryByText("spamReference")).not.toBeInTheDocument();
  expect(useSpamDecisionStore.getState().decisions["dm:message"]?.status).toBe("dismissed");
  cleanup();
  useAuthStore.setState({ user: null });
});
it("keeps the row and exposes errors when a decision fails", async () => {
  vi.mocked(decideSpam).mockResolvedValue({ success: false, error: "offline" });
  render(<SpamInbox />);
  fireEvent.click(await screen.findByRole("button", { name: "spamDismiss" }));
  expect(await screen.findByRole("alert")).toBeInTheDocument();
  expect(screen.getByText("spamReference")).toBeInTheDocument();
});
it("ignores a late restore after same-account reauthentication", async () => {
  useAuthStore.setState({ user: { id: "reader" } as NonNullable<ReturnType<typeof useAuthStore.getState>["user"]> });
  let finish!: (value: Awaited<ReturnType<typeof decideSpam>>) => void;
  vi.mocked(decideSpam).mockReturnValueOnce(new Promise((resolve) => { finish = resolve; }));
  render(<SpamInbox />);
  fireEvent.click(await screen.findByRole("button", { name: "spamRestore" }));
  const options = vi.mocked(decideSpam).mock.calls[0][2]!;
  act(() => { clearTokens(); useAuthStore.setState({ user: { id: "reader" } as NonNullable<ReturnType<typeof useAuthStore.getState>["user"]> }); });
  expect(options.signal?.aborted).toBe(true);
  expect(options.isCurrent?.()).toBe(false);
  await act(async () => { finish({ success: true }); });
  expect(await screen.findByText("spamReference")).toBeInTheDocument();
  expect(useSpamDecisionStore.getState().decisions).toEqual({});
});
it("recovers from a rejected initial load through refresh", async () => {
  vi.mocked(listSpam).mockRejectedValueOnce(new Error("offline"));
  render(<SpamInbox />);
  expect(await screen.findByRole("alert")).toBeInTheDocument();
  expect(screen.queryByRole("status")).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "spamRefresh" }));
  expect(await screen.findByText("spamReference")).toBeInTheDocument();
});
it("retains the row and releases pending actions after a rejected decision", async () => {
  vi.mocked(decideSpam).mockRejectedValueOnce(new Error("offline"));
  render(<SpamInbox />);
  fireEvent.click(await screen.findByRole("button", { name: "spamDismiss" }));
  expect(await screen.findByRole("alert")).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "spamDismiss" })).toBeEnabled();
  expect(screen.getByText("spamReference")).toBeInTheDocument();
});
it("keeps existing rows and allows paging retry after a network rejection", async () => {
  vi.mocked(listSpam).mockResolvedValueOnce({ success: true, data: { entries: [entry], next_cursor: "next" } });
  vi.mocked(listSpam).mockRejectedValueOnce(new Error("offline"));
  render(<SpamInbox />);
  fireEvent.click(await screen.findByRole("button", { name: "loadMore" }));
  expect(await screen.findByRole("alert")).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "loadMore" })).toBeEnabled();
  expect(screen.getByText("spamReference")).toBeInTheDocument();
  vi.mocked(listSpam).mockResolvedValueOnce({ success: true, data: { entries: [{ ...entry, message_id: "retry" }] } });
  fireEvent.click(screen.getByRole("button", { name: "loadMore" }));
  await waitFor(() => expect(screen.getAllByText("spamReference")).toHaveLength(2));
});
it("clears the previous account's rows while the next account loads", async () => {
  useAuthStore.setState({ user: { id: "first" } as NonNullable<ReturnType<typeof useAuthStore.getState>["user"]> });
  let finish!: (value: Awaited<ReturnType<typeof listSpam>>) => void;
  vi.mocked(listSpam).mockResolvedValueOnce({ success: true, data: { entries: [entry] } });
  vi.mocked(listSpam).mockReturnValueOnce(new Promise((resolve) => { finish = resolve; }));
  render(<SpamInbox />);
  await screen.findByText("spamReference");
  act(() => useAuthStore.setState({ user: { id: "second" } as NonNullable<ReturnType<typeof useAuthStore.getState>["user"]> }));
  expect(screen.queryByText("spamReference")).not.toBeInTheDocument();
  expect(screen.getByRole("status")).toBeInTheDocument();
  await act(async () => { finish({ success: true, data: { entries: [] } }); });
  expect(screen.getByText("spamEmpty")).toBeInTheDocument();
  cleanup();
  useAuthStore.setState({ user: null });
});
it("opens an explicit spam report without offering unavailable plaintext", async () => {
  vi.mocked(listSpam).mockResolvedValue({success:true,data:{entries:[{...entry,author_id:"sender"}]}});
  render(<SpamInbox />);
  fireEvent.click(await screen.findByRole("button",{name:"spamReport"}));
  expect(screen.getByText("reportTitle")).toBeInTheDocument();
  expect(screen.getByRole("button",{name:"reportReasonSpam"})).toHaveClass("selected");
  expect(screen.queryByRole("checkbox")).not.toBeInTheDocument();
  expect(screen.getByRole("button",{name:"reportSubmit"})).toBeDisabled();
});
it("removes only after successful dismissal and supports cursor paging", async () => {
  vi.mocked(listSpam).mockResolvedValueOnce({ success: true, data: { entries: [entry], next_cursor: "next" } });
  vi.mocked(listSpam).mockResolvedValueOnce({ success: true, data: { entries: [{ ...entry, message_id: "second" }] } });
  render(<SpamInbox />);
  fireEvent.click(await screen.findByRole("button", { name: "loadMore" }));
  await waitFor(() => expect(screen.getAllByText("spamReference")).toHaveLength(2));
  expect(listSpam).toHaveBeenLastCalledWith("next", expect.any(AbortSignal), expect.any(Function));
  fireEvent.click(screen.getAllByRole("button", { name: "spamDismiss" })[0]);
  await waitFor(() => expect(screen.getAllByText("spamReference")).toHaveLength(1));
  expect(decideSpam).toHaveBeenCalledWith(entry, "dismiss", { signal: expect.any(AbortSignal), isCurrent: expect.any(Function) });
});
it("ignores an old paging response after refresh and shows loading instead of empty", async () => {
  let finish!: (value: Awaited<ReturnType<typeof listSpam>>) => void;
  vi.mocked(listSpam).mockResolvedValueOnce({ success: true, data: { entries: [entry], next_cursor: "next" } });
  vi.mocked(listSpam).mockReturnValueOnce(new Promise((resolve) => { finish = resolve; }));
  vi.mocked(listSpam).mockResolvedValueOnce({ success: true, data: { entries: [{ ...entry, message_id: "fresh", unavailable:true }] } });
  render(<SpamInbox />);
  expect(screen.getByRole("status")).toBeInTheDocument();
  expect(screen.queryByText("spamEmpty")).not.toBeInTheDocument();
  fireEvent.click(await screen.findByRole("button", {name:"loadMore"}));
  fireEvent.click(screen.getByRole("button", {name:"spamRefresh"}));
  expect(await screen.findByText("spamUnavailable")).toBeInTheDocument();
  await act(async () => { finish({success:true,data:{entries:[{...entry,message_id:"stale"}]}}); });
  expect(screen.queryByText("spamReference")).not.toBeInTheDocument();
  expect(screen.getByText("spamUnavailable")).toBeInTheDocument();
});
