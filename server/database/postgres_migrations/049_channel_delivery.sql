CREATE FUNCTION channel_attachment_ready() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.channel_file_index IS NOT NULL THEN
  UPDATE channel_attachment_jobs SET status='ready',attachment_id=NEW.id,error=NULL,updated_at=CURRENT_TIMESTAMP WHERE message_id=NEW.message_id AND file_index=NEW.channel_file_index AND status='preparing';
  IF NOT FOUND THEN RAISE EXCEPTION 'attachment preparation expired'; END IF;
 END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER channel_attachment_ready AFTER INSERT ON attachments FOR EACH ROW EXECUTE FUNCTION channel_attachment_ready();
CREATE FUNCTION channel_message_sequence() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  UPDATE channels SET last_source_sequence=last_source_sequence+1 WHERE id=NEW.channel_id RETURNING last_source_sequence INTO NEW.source_sequence;
  IF NOT FOUND THEN RAISE EXCEPTION 'channel source requires channel'; END IF;
 ELSIF NEW.source_sequence IS DISTINCT FROM OLD.source_sequence THEN
  RAISE EXCEPTION 'channel source sequence is immutable';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER channel_message_sequence BEFORE INSERT OR UPDATE OF source_sequence ON messages FOR EACH ROW EXECUTE FUNCTION channel_message_sequence();
CREATE FUNCTION channel_message_event() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE m RECORD; seq BIGINT; operation TEXT;
BEGIN
 IF TG_OP='DELETE' THEN m:=OLD; operation:='message_delete'; ELSE m:=NEW; operation:=CASE WHEN TG_OP='INSERT' THEN 'message_create' ELSE 'message_update' END; END IF;
 UPDATE channels SET last_event_sequence=last_event_sequence+1 WHERE id=m.channel_id RETURNING last_event_sequence INTO seq;
 -- Cascading channel deletion needs no replay into a vanished channel.
 IF seq IS NOT NULL THEN
  INSERT INTO channel_delivery_outbox(channel_id,channel_sequence,message_id,op,payload,ready)
  VALUES(m.channel_id,seq,m.id,operation,
   CASE WHEN TG_OP='DELETE' THEN jsonb_build_object('id',m.id,'channel_id',m.channel_id) ELSE to_jsonb(m) END,
   TG_OP<>'INSERT');
 END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER channel_message_event AFTER INSERT OR UPDATE OF content,ciphertext,e2ee_metadata,edited_at OR DELETE ON messages FOR EACH ROW EXECUTE FUNCTION channel_message_event();
CREATE FUNCTION channel_notification_event() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE seq BIGINT;
BEGIN
 IF NEW.channel_id IS NOT NULL AND NEW.message_id IS NOT NULL AND
  (NEW.kind IN ('mention','reply') OR (NEW.kind='system' AND NEW.payload::jsonb->>'source'='channel' AND NEW.payload::jsonb->>'action'='incoming_message')) THEN
  UPDATE channels SET last_event_sequence=last_event_sequence+1 WHERE id=NEW.channel_id RETURNING last_event_sequence INTO seq;
  IF seq IS NULL THEN RETURN NULL; END IF;
  INSERT INTO channel_delivery_outbox(channel_id,channel_sequence,message_id,op,recipient_id,payload,ready)
  VALUES(NEW.channel_id,seq,NEW.message_id,'notification_create',NEW.user_id,to_jsonb(NEW)||jsonb_build_object('payload',NEW.payload::jsonb),FALSE);
 END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER channel_notification_event AFTER INSERT ON notifications FOR EACH ROW EXECUTE FUNCTION channel_notification_event();
