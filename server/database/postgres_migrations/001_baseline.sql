-- PostgreSQL baseline corresponding to SQLite migrations through 100.
-- IDs and opaque encrypted values remain TEXT; epoch values remain BIGINT.
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;
CREATE FUNCTION hichat_ascii_lower(value TEXT) RETURNS TEXT LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT translate(value, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz') $$;
CREATE FUNCTION json_valid(value TEXT) RETURNS BOOLEAN LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN PERFORM value::jsonb; RETURN TRUE; EXCEPTION WHEN invalid_text_representation THEN RETURN FALSE; END $$;

